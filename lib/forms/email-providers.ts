function registrableDomain(domain: string) {
  const parts = domain.split(".").filter(Boolean);
  if (parts.length < 2) return domain;
  return parts.slice(-2).join(".");
}

export function emailDomain(email: string) {
  const at = email.lastIndexOf("@");
  if (at < 1) return "";
  return email.slice(at + 1).trim().toLowerCase();
}

export function isTrustedEmailAddress(email: string) {
  const domain = emailDomain(email);
  if (!domain || domain.startsWith(".") || domain.endsWith(".")) return false;
  if (domain.includes("..") || /[^a-z0-9.-]/i.test(domain)) return false;
  if (/^\d{1,3}(\.\d{1,3}){3}$/.test(domain)) return false;

  const labels = domain.split(".");
  if (labels.length < 2) return false;
  const tld = labels.at(-1) ?? "";
  if (tld.length < 2 || tld.length > 24) return false;

  if (DISPOSABLE_EMAIL_DOMAINS.has(domain) || DISPOSABLE_EMAIL_DOMAINS.has(registrableDomain(domain))) {
    return false;
  }

  if (
    /(^|\.)(tempmail|temp-mail|mailinator|guerrillamail|yopmail|throwaway|trashmail|10minutemail|discardmail|fakeinbox)/i.test(
      domain,
    )
  ) {
    return false;
  }

  if (TRUSTED_PUBLIC_PROVIDERS.has(domain) || TRUSTED_PUBLIC_PROVIDERS.has(registrableDomain(domain))) {
    return true;
  }

  if (BLOCKED_EMAIL_TLDS.has(tld)) return false;

  return labels.length >= 2 && !domain.endsWith(".example");
}
